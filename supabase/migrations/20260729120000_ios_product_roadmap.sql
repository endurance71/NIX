CREATE OR REPLACE FUNCTION public.create_friend_invite(invite_channel TEXT)
RETURNS TABLE(invite_token TEXT, expires_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor_id UUID := auth.uid();
  normalized_channel TEXT := lower(trim(invite_channel));
  token_plain TEXT;
  token_digest TEXT;
  expiration TIMESTAMPTZ;
BEGIN
  IF actor_id IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF private.is_account_restricted(actor_id) THEN RAISE EXCEPTION 'Account is restricted'; END IF;
  IF normalized_channel NOT IN ('qr', 'share') THEN RAISE EXCEPTION 'Invalid invite channel'; END IF;

  token_plain := replace(extensions.gen_random_uuid()::TEXT, '-', '')
    || replace(extensions.gen_random_uuid()::TEXT, '-', '');
  token_digest := md5(token_plain);
  expiration := CASE normalized_channel
    WHEN 'share' THEN now() + INTERVAL '7 days'
    ELSE now() + INTERVAL '5 minutes'
  END;

  INSERT INTO public.friend_invites(created_by, token_hash, channel, expires_at)
  VALUES (actor_id, token_digest, normalized_channel, expiration);
  RETURN QUERY SELECT token_plain, expiration;
END;
$$;

