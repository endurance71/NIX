CREATE OR REPLACE FUNCTION public.request_data_export()
RETURNS public.data_export_jobs
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE result public.data_export_jobs;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF EXISTS (
    SELECT 1 FROM public.data_export_jobs j
    WHERE j.user_id = auth.uid()
      AND (
        j.status IN ('queued', 'processing')
        OR j.requested_at > now() - INTERVAL '24 hours'
      )
  ) THEN
    RAISE EXCEPTION 'Data export is already active or was requested recently';
  END IF;
  INSERT INTO public.data_export_jobs(user_id)
  VALUES (auth.uid())
  RETURNING * INTO result;
  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.request_data_export() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.request_data_export() TO authenticated;

CREATE OR REPLACE FUNCTION public.cleanup_expired_data_exports()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  UPDATE public.data_export_jobs
  SET status = 'expired', updated_at = now()
  WHERE status = 'ready' AND expires_at <= now();
  DELETE FROM public.data_export_jobs
  WHERE requested_at < now() - INTERVAL '30 days';
END;
$$;

REVOKE ALL ON FUNCTION public.cleanup_expired_data_exports() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cleanup_expired_data_exports() TO service_role;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    PERFORM cron.unschedule(jobid)
    FROM cron.job
    WHERE jobname = 'nix-data-export-cleanup';
    PERFORM cron.schedule(
      'nix-data-export-cleanup',
      '40 3 * * *',
      'SELECT public.cleanup_expired_data_exports();'
    );
  END IF;
END
$$;
