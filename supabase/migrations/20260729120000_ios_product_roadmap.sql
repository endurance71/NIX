CREATE OR REPLACE FUNCTION public.get_user_activation_state()
RETURNS TABLE(
  has_friend BOOLEAN,
  has_sent_nix BOOLEAN,
  skipped_at TIMESTAMPTZ,
  dismissed_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  last_shown_at TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  actor_id UUID := auth.uid();
  friend_exists BOOLEAN;
  nix_exists BOOLEAN;
  activation public.user_activation_state%ROWTYPE;
BEGIN
  IF actor_id IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  SELECT EXISTS (
    SELECT 1 FROM public.friendships f
    WHERE f.status = 'accepted'
      AND (f.user_id = actor_id OR f.friend_id = actor_id)
  ) INTO friend_exists;
  SELECT EXISTS (
    SELECT 1 FROM public.nixes n WHERE n.sender_id = actor_id
  ) INTO nix_exists;

  INSERT INTO public.user_activation_state(user_id, completed_at)
  VALUES (actor_id, CASE WHEN friend_exists AND nix_exists THEN now() ELSE NULL END)
  ON CONFLICT (user_id) DO UPDATE
  SET completed_at = CASE
        WHEN public.user_activation_state.completed_at IS NOT NULL
          THEN public.user_activation_state.completed_at
        WHEN friend_exists AND nix_exists THEN now()
        ELSE NULL
      END,
      updated_at = now()
  RETURNING * INTO activation;

  RETURN QUERY SELECT friend_exists, nix_exists, activation.skipped_at,
    activation.dismissed_at, activation.completed_at, activation.last_shown_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_user_activation_state(
  p_action TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF p_action NOT IN ('shown', 'skip', 'dismiss') THEN RAISE EXCEPTION 'Invalid activation action'; END IF;
  INSERT INTO public.user_activation_state(
    user_id, skipped_at, dismissed_at, last_shown_at, updated_at
  )
  VALUES (
    auth.uid(),
    CASE WHEN p_action = 'skip' THEN now() ELSE NULL END,
    CASE WHEN p_action = 'dismiss' THEN now() ELSE NULL END,
    CASE WHEN p_action = 'shown' THEN now() ELSE NULL END,
    now()
  )
  ON CONFLICT (user_id) DO UPDATE
  SET skipped_at = CASE WHEN p_action = 'skip' THEN now() ELSE public.user_activation_state.skipped_at END,
      dismissed_at = CASE WHEN p_action = 'dismiss' THEN now() ELSE public.user_activation_state.dismissed_at END,
      last_shown_at = CASE WHEN p_action = 'shown' THEN now() ELSE public.user_activation_state.last_shown_at END,
      updated_at = now();
END;
$$;

