CREATE OR REPLACE FUNCTION public.revoke_other_app_installations(p_current_installation_id UUID)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE affected INTEGER;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  UPDATE public.app_installations
  SET revoked_at = now(), updated_at = now()
  WHERE user_id = auth.uid()
    AND installation_id <> p_current_installation_id
    AND revoked_at IS NULL;
  GET DIAGNOSTICS affected = ROW_COUNT;

  UPDATE public.push_devices
  SET enabled = FALSE, disabled_reason = 'other_sessions_signed_out', updated_at = now()
  WHERE user_id = auth.uid() AND installation_id <> p_current_installation_id;
  RETURN affected;
END;
$$;

