CREATE OR REPLACE FUNCTION public.set_conversation_mute(
  p_peer_id UUID,
  p_muted_until TIMESTAMPTZ,
  p_indefinite BOOLEAN DEFAULT FALSE
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
  IF p_peer_id IS NULL OR p_peer_id = auth.uid() THEN RAISE EXCEPTION 'Invalid peer'; END IF;
  IF NOT p_indefinite AND (p_muted_until IS NULL OR p_muted_until <= now()) THEN
    DELETE FROM public.conversation_mutes
    WHERE owner_user_id = auth.uid() AND peer_user_id = p_peer_id;
    RETURN;
  END IF;
  INSERT INTO public.conversation_mutes(owner_user_id, peer_user_id, muted_until, updated_at)
  VALUES (auth.uid(), p_peer_id, CASE WHEN p_indefinite THEN NULL ELSE p_muted_until END, now())
  ON CONFLICT (owner_user_id, peer_user_id) DO UPDATE
  SET muted_until = EXCLUDED.muted_until, updated_at = now();
END;
$$;

