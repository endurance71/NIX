CREATE OR REPLACE FUNCTION public.record_product_analytics_event(
  p_installation_id UUID,
  p_event_name TEXT,
  p_app_version TEXT,
  p_locale TEXT,
  p_properties JSONB DEFAULT '{}'::JSONB
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NULL OR p_installation_id IS NULL THEN RETURN FALSE; END IF;
  IF NOT COALESCE((
    SELECT pref.enabled
    FROM public.product_analytics_preferences pref
    WHERE pref.user_id = auth.uid()
  ), FALSE) THEN
    RETURN FALSE;
  END IF;
  IF p_event_name NOT IN (
    'onboarding_completed', 'inbox_search_used', 'invite_shared', 'invite_opened',
    'invite_redeemed', 'first_friend_accepted', 'first_nix_sent', 'nix_opened',
    'text_outbox_retry', 'push_preference_changed', 'data_export_requested'
  ) THEN
    RAISE EXCEPTION 'Unsupported analytics event';
  END IF;
  IF lower(p_locale) NOT IN ('pl', 'en') THEN RAISE EXCEPTION 'Unsupported locale'; END IF;
  IF jsonb_typeof(COALESCE(p_properties, '{}'::JSONB)) <> 'object'
     OR octet_length(COALESCE(p_properties, '{}'::JSONB)::TEXT) > 2048 THEN
    RAISE EXCEPTION 'Invalid analytics properties';
  END IF;

  INSERT INTO public.product_analytics_events(
    installation_id, event_name, app_version, locale, properties
  )
  VALUES (
    p_installation_id,
    p_event_name,
    left(NULLIF(trim(p_app_version), ''), 40),
    lower(p_locale),
    COALESCE(p_properties, '{}'::JSONB)
  );
  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.rollup_and_cleanup_product_analytics()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.product_analytics_daily(event_date, event_name, locale, event_count)
  SELECT created_at::DATE, event_name, locale, COUNT(*)
  FROM public.product_analytics_events
  WHERE created_at < date_trunc('day', now())
  GROUP BY created_at::DATE, event_name, locale
  ON CONFLICT (event_date, event_name, locale) DO UPDATE
  SET event_count = EXCLUDED.event_count;

  DELETE FROM public.product_analytics_events
  WHERE created_at < now() - INTERVAL '30 days';
END;
$$;

REVOKE ALL ON FUNCTION public.set_product_analytics_consent(BOOLEAN) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.record_product_analytics_event(UUID, TEXT, TEXT, TEXT, JSONB) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.rollup_and_cleanup_product_analytics() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_product_analytics_consent(BOOLEAN) TO authenticated;
GRANT EXECUTE ON FUNCTION public.record_product_analytics_event(UUID, TEXT, TEXT, TEXT, JSONB) TO authenticated;
GRANT EXECUTE ON FUNCTION public.rollup_and_cleanup_product_analytics() TO service_role;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    PERFORM cron.unschedule(jobid)
    FROM cron.job
    WHERE jobname = 'nix-product-analytics-cleanup';
    PERFORM cron.schedule(
      'nix-product-analytics-cleanup',
      '20 3 * * *',
      'SELECT public.rollup_and_cleanup_product_analytics();'
    );
  END IF;
END
$$;

